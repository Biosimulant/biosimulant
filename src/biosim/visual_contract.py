from collections import Counter
from typing import Any
from urllib.parse import urlsplit

VISUAL_CONTRACT_VERSION = "1"
MAX_VISUAL_BYTES = 2_000_000
MAX_VISUALS = 64
MAX_POINTS = 10_000

